-- | A strict, finger-tree style deque.
--
-- * worst-case O(1) 'cons', 'snoc', 'uncons', 'unsnoc', 'size'
-- * O(log n) 'lookup', 'append', 'take', 'drop'
-- * O(n) 'fromList', 'toList'
-- * no laziness anywhere: every field is strict, nothing is a thunk
--
module Unison.Util.Deque
  ( -- * The type
    Deque
  , Seq
  , pattern Empty, pattern (:<|), pattern (:|>)
    -- * Construction
  , empty, singleton
  , cons, snoc, append
  , (<|), (|>), (><)
  , fromList, fromFunction
    -- * Queries
  , size, length, null
  , lookup
  , toList
    -- * Taking apart
  , uncons, unsnoc
  , take, drop, splitAt
    -- * Whole-sequence transformations (these rebuild the sequence)
  , sort, sortBy, unstableSort, unstableSortBy
  , intersperse, reverse
    -- * For tests
  , valid
  ) where

