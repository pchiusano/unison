-- Append, O(log (min n m)).
--
-- A deque's sequence at level k is  prefix_k ++ (nodes of level k+1, unpacked)
-- ++ suffix_k.  So for A ++ B, level k of the result keeps A's prefix and B's
-- suffix, and the seam  suffix_k(A) ++ (nodes from the seam one level up) ++
-- prefix_k(B)  is packed into nodes that join the sequence of level k+1.  The
-- seam is not a multiple of eight, so those nodes have eight, three or two
-- children: that is what the node sizes are for.
--
-- When one side runs out of levels, the nodes still carried are pushed onto
-- the near end of the other side's next level; a digit that overflows keeps
-- five elements and hands the rest down as nodes, which soon stops.  The
-- levels below that are shared with the argument.
--
-- Each level of the result is put on top of the levels below it with
-- 'mkRest', which repairs it if it is red, so the digits taken from A and B
-- need no preparation.

-- Level k of A and of B (with the levels below each) and the carry (c nodes,
-- in sequence order) from the seam above: level k of the result, and the
-- levels below it.  'fix' repairs a red level that isn't the bottom.
catLvl :: (x -> Int)
       -> (Lvl x -> Rest (Node x) -> (# Lvl x, Rest (Node x) #))
       -> Int -> SList x
       -> Lvl x -> Rest (Node x) -> Lvl x -> Rest (Node x)
       -> (# Lvl x, Rest (Node x) #)
catLvl sz fix = go
  where
    go !c carry la@(Lvl pA sA) ra lb@(Lvl pB sB) rb
      -- both end here and fit in one level
      | endA, endB, total <= 2 * bGreen =
          let xs = appendS (dFwd pA) (revApp (dBwd sA) (appendS carry (appendS (dFwd pB) (revS (dBwd sB)))))
          in (# splitLvl sz (if total <= 3 then total else total `div` 2) total xs, noRest #)
      | m == 0 = (# Lvl pA sB, catRest 0 SEmpty ra rb #)
      | m >= 2 = let !nodes = packF sz m seam in (# Lvl pA sB, catRest (lenS nodes) nodes ra rb #)
      -- One element can't make a node.  It is there because a digit next to
      -- the seam is empty.  If that is in a red level, repair the level and
      -- try again; if it is in a bottom level, the seam borrows a neighbour
      -- from the bottom level's other digit.
      | dcount sA == 0, not endA = case fix la ra of (# la', ra' #) -> go c carry la' ra' lb rb
      | dcount pB == 0, not endB = case fix lb rb of (# lb', rb' #) -> go c carry la ra lb' rb'
      | dcount sA == 0 = case dInit sz pA of
          (# pA', x #) -> let !nodes = packF sz 2 (SCons x seam) in (# Lvl pA' sB, catRest 1 nodes ra rb #)
      | otherwise = case dInit sz sB of
          (# sB', x #) -> let !nodes = packF sz 2 (appendS seam (SCons x SEmpty)) in (# Lvl pA sB', catRest 1 nodes ra rb #)
      where
        endA  = isNoRest ra
        endB  = isNoRest rb
        m     = dcount sA + c + dcount pB
        total = dcount pA + m + dcount sB
        seam  = revApp (dBwd sA) (appendS carry (dFwd pB))
{-# INLINE catLvl #-}

-- The levels below the top: A's, the carry, B's.
catRest :: Int -> SList (Node x) -> Rest (Node x) -> Rest (Node x) -> Rest (Node x)
catRest !c carry ra rb = case viewRest ra of
  Nothing -> growFront c carry rb
  Just (la, ra1) -> case viewRest rb of
    Nothing -> growBack c carry ra
    Just (lb, rb1) -> case catLvl nodeSize fixLvl c carry la ra1 lb rb1 of
      (# l, lower #) -> mkRest l lower

fixLvl :: Lvl (Node x) -> Rest (Node (Node x)) -> (# Lvl (Node x), Rest (Node (Node x)) #)
fixLvl l r = case viewRest (mkRest l r) of
  Just (l', r') -> (# l', r' #)
  Nothing       -> error "fixLvl: the level vanished"

-- Push c nodes (in sequence order) onto the front of these levels.
growFront :: Int -> SList (Node x) -> Rest (Node x) -> Rest (Node x)
growFront !c carry rb
  | c == 0 = rb
  | otherwise = case viewRest rb of
      Nothing -> mkRest (Lvl (mkDig nodeSize c carry) dnil) noRest
      Just (Lvl (Dig n z l) s, rb1)
        | c + n <= bGreen -> mkRest (Lvl (Dig (c + n) (z + sumSz nodeSize carry) (appendS carry l)) s) rb1
        | otherwise ->
            let allL   = appendS carry l
                !nodes = packF nodeSize (c + n - 5) (dropS 5 allL)
            in mkRest (Lvl (mkDig nodeSize 5 (takeS 5 allL)) s) (growFront (lenS nodes) nodes rb1)

-- ... or onto the back.
growBack :: Int -> SList (Node x) -> Rest (Node x) -> Rest (Node x)
growBack !c carry ra
  | c == 0 = ra
  | otherwise = case viewRest ra of
      Nothing -> mkRest (Lvl (mkDig nodeSize c carry) dnil) noRest
      Just (Lvl p (Dig n z l), ra1)
        | c + n <= bGreen -> mkRest (Lvl p (Dig (c + n) (z + sumSz nodeSize carry) (revApp carry l))) ra1
        | otherwise ->
            let allB   = revApp carry l                   -- last element first
                !nodes = packF nodeSize (c + n - 5) (revS (dropS 5 allB))
            in mkRest (Lvl p (mkDig nodeSize 5 (takeS 5 allB))) (growBack (lenS nodes) nodes ra1)

-- Appending a small deque element by element beats the general algorithm,
-- and leaves full nodes behind.
bulkLimit :: Int
bulkLimit = 8

-- | Concatenate.  O(log (min n m)).
append :: Deque a -> Deque a -> Deque a
append Nil b = b
append a Nil = a
append a@(Deque szA npA plA nsA slA tlA subsA) b@(Deque szB npB plB nsB slB tlB subsB)
  -- A small single-level deque joins the digit next to it in one step.  If
  -- the digit stays green nothing else changes; otherwise one repair (which
  -- sheds a node of eight) makes it green, so it may get up to bGreen + wNode.
  | szB <= bulkLimit, YN <- tlB, SN <- subsB, nsA + szB <= bGreen + wNode =
      let s' = appendS slB (revApp plB slA)
      in if nsA >= 1 && nsA + szB <= bGreen
           then Deque (szA + szB) npA plA (nsA + szB) s' tlA subsA
           else mkTop (szA + szB) (Dig npA 0 plA) (Dig (nsA + szB) 0 s') (Rest tlA subsA)
  | szA <= bulkLimit, YN <- tlA, SN <- subsA, npB + szA <= bGreen + wNode =
      let p' = appendS plA (revApp slA plB)
      in if npB >= 1 && npB + szA <= bGreen
           then Deque (szA + szB) (npB + szA) p' nsB slB tlB subsB
           else mkTop (szA + szB) (Dig (npB + szA) 0 p') (Dig nsB 0 slB) (Rest tlB subsB)
  | szB <= bulkLimit = foldlD' snoc a b
  | szA <= bulkLimit = front a b
  | otherwise =
      case catLvl (const 1) (\_ _ -> error "append: a red top level") 0 SEmpty
             (Lvl (Dig npA 0 plA) (Dig nsA 0 slA)) (Rest tlA subsA)
             (Lvl (Dig npB 0 plB) (Dig nsB 0 slB)) (Rest tlB subsB) of
        (# Lvl p s, lower #) -> mkTop (szA + szB) p s lower
  where
    front x acc = case unsnoc x of            -- consume a from its back, cons onto b
      Nothing       -> acc
      Just (x', e)  -> front x' (cons e acc)

