------------------------------------------------------------------------
-- Parameters.  A repair moves one Node of 'wNode' elements between a level
-- and the one below.  Digit sizes: green 2..bGreen, yellow 1 and bGreen+1,
-- red 0 and bGreen+2.  Any bGreen >= wNode + 1 works (wNode = 2, bGreen = 3
-- is the classic 0..5 scheme); the minimum keeps repairs cheapest.

wNode :: Int
wNode = 8

bGreen :: Int
bGreen = wNode + 1

------------------------------------------------------------------------
-- Strict lists (digits), and nodes.  Digits are short lists; the bulk of the
-- data lives in nodes.  A node's first field is the number of leaves under
-- it.  Nodes made by repairs (shedding a full digit) have eight children;
-- 'append' may also make nodes of three or two.

data SList a = SEmpty | SCons !a !(SList a)

-- If built via `cons` and `snoc`, a `Deque` will only contain
-- `N8` nodes. `N2` and `N3` are needed for symmetry breaking in `append`,
-- and can sometimes be generated by `take` and `drop`.
data Node a
  = N8 !Int !a !a !a !a !a !a !a !a
  | N3 !Int !a !a !a
  | N2 !Int !a !a

nodeSize :: Node a -> Int
nodeSize (N8 n _ _ _ _ _ _ _ _) = n
nodeSize (N3 n _ _ _)           = n
nodeSize (N2 n _ _)             = n
{-# INLINE nodeSize #-}

nodeArity :: Node a -> Int
nodeArity (N8 {}) = 8
nodeArity (N3 {}) = 3
nodeArity (N2 {}) = 2
{-# INLINE nodeArity #-}

-- first eight cells of a list that runs in sequence order; the node of eight
-- leaves (level 1) or of eight nodes (deeper)
nodeFromFwd :: SList a -> Node a
nodeFromFwd (SCons a (SCons b (SCons c (SCons d (SCons e (SCons f (SCons g (SCons h _))))))))
  = N8 8 a b c d e f g h
nodeFromFwd _ = error "nodeFromFwd: short list"

nodeFromBwd :: SList a -> Node a
nodeFromBwd (SCons h (SCons g (SCons f (SCons e (SCons d (SCons c (SCons b (SCons a _))))))))
  = N8 8 a b c d e f g h
nodeFromBwd _ = error "nodeFromBwd: short list"

nodeFromFwdN :: SList (Node y) -> Node (Node y)
nodeFromFwdN (SCons a (SCons b (SCons c (SCons d (SCons e (SCons f (SCons g (SCons h _))))))))
  = N8 (nodeSize a + nodeSize b + nodeSize c + nodeSize d + nodeSize e + nodeSize f + nodeSize g + nodeSize h)
       a b c d e f g h
nodeFromFwdN _ = error "nodeFromFwdN: short list"

nodeFromBwdN :: SList (Node y) -> Node (Node y)
nodeFromBwdN (SCons h (SCons g (SCons f (SCons e (SCons d (SCons c (SCons b (SCons a _))))))))
  = N8 (nodeSize a + nodeSize b + nodeSize c + nodeSize d + nodeSize e + nodeSize f + nodeSize g + nodeSize h)
       a b c d e f g h
nodeFromBwdN _ = error "nodeFromBwdN: short list"

nodeToFwd, nodeToBwd :: Node a -> SList a
nodeToFwd (N8 _ a b c d e f g h) =
  SCons a (SCons b (SCons c (SCons d (SCons e (SCons f (SCons g (SCons h SEmpty)))))))
nodeToFwd (N3 _ a b c) = SCons a (SCons b (SCons c SEmpty))
nodeToFwd (N2 _ a b)   = SCons a (SCons b SEmpty)
nodeToBwd (N8 _ a b c d e f g h) =
  SCons h (SCons g (SCons f (SCons e (SCons d (SCons c (SCons b (SCons a SEmpty)))))))
nodeToBwd (N3 _ a b c) = SCons c (SCons b (SCons a SEmpty))
nodeToBwd (N2 _ a b)   = SCons b (SCons a SEmpty)

-- the k-th child (0-based)
nodeAt :: Int -> Node a -> a
nodeAt k (N8 _ a b c d e f g h) = case k of
  0 -> a; 1 -> b; 2 -> c; 3 -> d; 4 -> e; 5 -> f; 6 -> g; _ -> h
nodeAt k (N3 _ a b c) = case k of { 0 -> a; 1 -> b; _ -> c }
nodeAt k (N2 _ a b)   = case k of { 0 -> a; _ -> b }

takeS :: Int -> SList a -> SList a
takeS 0 _            = SEmpty
takeS k (SCons x r)  = SCons x (takeS (k - 1) r)
takeS _ SEmpty       = SEmpty

dropS :: Int -> SList a -> SList a
dropS 0 l            = l
dropS k (SCons _ r)  = dropS (k - 1) r
dropS _ SEmpty       = SEmpty

appendS :: SList a -> SList a -> SList a
appendS SEmpty ys       = ys
appendS (SCons x r) ys  = SCons x (appendS r ys)

------------------------------------------------------------------------
-- A digit is a buffer with its element count and the number of leaves under
-- its elements.  The list runs outermost element first: front of a prefix,
-- back of a suffix.  So cons/snoc/uncons/unsnoc are plain list cons/uncons.
-- Only the repair step touches the inner end.
--
-- The leaf count is what lets 'index' skip over a whole digit without
-- touching its nodes.  It is kept up to date for digits below the top level
-- (whose elements are nodes); for the top level, where an element is one
-- leaf, it is not maintained (the count is the leaf count).

data Dig a = Dig !Int !Int !(SList a)

dnil :: Dig a
dnil = Dig 0 0 SEmpty

dcount :: Dig a -> Int
dcount (Dig n _ _) = n
{-# INLINE dcount #-}

dpop :: Dig a -> (a, Dig a)                    -- outer end; needs count >= 1
dpop (Dig n z (SCons x l)) = (x, Dig (n - 1) z l)
dpop (Dig _ _ SEmpty)      = error "dpop: empty digit"
{-# INLINE dpop #-}

-- the same, keeping the leaf count (given the size of one element)
dpushS :: (a -> Int) -> a -> Dig a -> Dig a
dpushS sz x (Dig n z l) = Dig (n + 1) (z + sz x) (SCons x l)
{-# INLINE dpushS #-}

dpopS :: (a -> Int) -> Dig a -> (a, Dig a)
dpopS sz (Dig n z (SCons x l)) = (x, Dig (n - 1) (z - sz x) l)
dpopS _ (Dig _ _ SEmpty)       = error "dpopS: empty digit"
{-# INLINE dpopS #-}

-- Shed the wNode innermost elements as a Node in sequence order.  The prefix
-- list runs in sequence order and the suffix list runs backwards, so each
-- matches straight into the node's fields.
shedP, shedS :: Dig a -> (Dig a, Node a)
shedP (Dig n z l) =
  let !k = n - wNode
      !front = Dig k z (takeS k l)
      !nd = nodeFromFwd (dropS k l)
  in (front, nd)
shedS (Dig n z l) =
  let !k = n - wNode
      !front = Dig k z (takeS k l)
      !nd = nodeFromBwd (dropS k l)
  in (front, nd)

-- The same one level down, where the elements are themselves nodes and the
-- new node's size is the sum of theirs.
shedPN, shedSN :: Dig (Node y) -> (Dig (Node y), Node (Node y))
shedPN (Dig n z l) =
  let !k = n - wNode
      !nd = nodeFromFwdN (dropS k l)
      !front = Dig k (z - nodeSize nd) (takeS k l)
  in (front, nd)
shedSN (Dig n z l) =
  let !k = n - wNode
      !nd = nodeFromBwdN (dropS k l)
      !front = Dig k (z - nodeSize nd) (takeS k l)
  in (front, nd)

-- Take a Node (of any arity) onto the inner end.
pullP, pullS :: Dig a -> Node a -> Dig a
pullP (Dig n z l) nd = Dig (n + nodeArity nd) (z + nodeSize nd) (appendS l (nodeToFwd nd))
pullS (Dig n z l) nd = Dig (n + nodeArity nd) (z + nodeSize nd) (appendS l (nodeToBwd nd))

------------------------------------------------------------------------
-- Levels: a prefix and a suffix.  The level's sequence is prefix ++ suffix
-- (a suffix's slots run back to front).

data Lvl a = Lvl {-# UNPACK #-} !(Dig a) {-# UNPACK #-} !(Dig a)

-- A level from its t elements in sequence order: the first k go to the
-- prefix, the rest to the suffix.
splitLvl :: (a -> Int) -> Int -> Int -> SList a -> Lvl a
splitLvl sz k t xs = Lvl (mkDig sz k (takeS k xs)) (mkDig sz (t - k) (revS (dropS k xs)))

isEmptyLvl :: Lvl a -> Bool
isEmptyLvl (Lvl p s) = dcount p == 0 && dcount s == 0

-- Colors: red < yellow < green.  The bottom level ignores an empty digit.
data Color = Red | Yellow | Green deriving (Eq, Ord, Show)

ccolor :: Int -> Color
ccolor n
  | n >= 2 && n <= bGreen = Green
  | n == 1 || n == bGreen + 1 = Yellow
  | otherwise = Red
{-# INLINE ccolor #-}

lcolorN :: Bool -> Int -> Int -> Color
lcolorN bottom np ns
  | bottom && np == 0 = if ns == 0 then Green else ccolor ns
  | bottom && ns == 0 = ccolor np
  | otherwise         = min (ccolor np) (ccolor ns)
{-# INLINE lcolorN #-}

lcolor :: Bool -> Lvl a -> Color
lcolor bottom (Lvl p s) = lcolorN bottom (dcount p) (dcount s)
{-# INLINE lcolor #-}

-- Push/pop at either end of a level's sequence (sz: size of one element,
-- for the leaf counts).
pushF, pushB :: (a -> Int) -> a -> Maybe (Lvl a) -> Lvl a
pushF sz e Nothing          = Lvl (dpushS sz e dnil) dnil
pushF sz e (Just (Lvl p s)) = Lvl (dpushS sz e p) s
pushB sz e Nothing          = Lvl dnil (dpushS sz e dnil)
pushB sz e (Just (Lvl p s)) = Lvl p (dpushS sz e s)

popF, popB :: (a -> Int) -> Lvl a -> Maybe (a, Lvl a)
popF sz (Lvl p s)
  | dcount p > 0 = case dpopS sz p of (x, p') -> Just (x, Lvl p' s)
  -- A bottom level with an empty prefix: share out what is left between the
  -- two digits, so that the pops that follow find a prefix.  (Up to three
  -- elements all go to the near digit.)
  | otherwise    = case revS (dBwd s) of
      SCons x xs -> let r = dcount s - 1
                    in Just (x, splitLvl sz (if r <= 3 then r else r `div` 2) r xs)
      SEmpty     -> Nothing
popB sz (Lvl p s)
  | dcount s > 0 = case dpopS sz s of (x, s') -> Just (x, Lvl p s')
  | otherwise    = case revS (dFwd p) of       -- the mirror image; xs runs back to front
      SCons x xs -> let r = dcount p - 1
                        k = if r <= 3 then r else r `div` 2
                    in Just (x, Lvl (mkDig sz (r - k) (revS (dropS k xs))) (mkDig sz k (takeS k xs)))
      SEmpty     -> Nothing

------------------------------------------------------------------------
-- General (slow-path) repair: make a level green using at most one
-- node-move per end of the level below.  Pushes happen before pulls so a
-- bottom level can feed itself.  Nothing for the next level means "absent";
-- the result is Nothing if the next level was (or became) an empty bottom.

makeGreen :: (Dig a -> (Dig a, Node a)) -> (Dig a -> (Dig a, Node a)) -> (a -> Int)
          -> Bool -> Lvl a -> Maybe (Lvl (Node a)) -> (Lvl a, Maybe (Lvl (Node a)))
makeGreen shP shS sz nextLast (Lvl p s) ml0 =
  let lastFlag = case ml0 of { Nothing -> True; Just _ -> nextLast }
      (p1, ml1)
        | dcount p > bGreen = case shP p of
            (p', nd) -> (p', Just (pushF nodeSize nd ml0))
        | otherwise = (p, ml0)
      (s1, ml2)
        | dcount s > bGreen = case shS s of
            (s', nd) -> (s', Just (pushB nodeSize nd ml1))
        | otherwise = (s, ml1)
      (p2, ml3)
        | dcount p1 < 2 = case ml2 >>= popF nodeSize of
            Just (nd, l') -> (pullP p1 nd, Just l')
            Nothing            -> (p1, ml2)
        | otherwise = (p1, ml2)
      (s2, ml4)
        | dcount s1 < 2 = case ml3 >>= popB nodeSize of
            Just (nd, l') -> (pullS s1 nd, Just l')
            Nothing            -> (s1, ml3)
        | otherwise = (s1, ml3)
      ml5 = case ml4 of
        Just l | lastFlag, isEmptyLvl l -> Nothing
        _                               -> ml4
      r' = Lvl p2 s2
  in case ml5 of
       Nothing -> (canonBottom sz r', Nothing)
       Just _  -> (r', ml5)

-- A bottom level with no level beneath it: rebalance its two digits.
canonBottom :: (a -> Int) -> Lvl a -> Lvl a
canonBottom sz l@(Lvl p s)
  | t <= 3          = if dcount s == 0 then l else Lvl (mkDig sz t xs) dnil
  | t <= 2 * bGreen = if ccolor (dcount p) == Green && ccolor (dcount s) == Green then l
                      else splitLvl sz (t `div` 2) t xs
  | otherwise       = l
  where t  = dcount p + dcount s
        xs = appendS (dFwd p) (revS (dBwd s))

------------------------------------------------------------------------
-- Levels are grouped K-T style.  The top level's digits live directly in
-- the Deque; below them come the yellow levels of the top run ('tl'), then
-- a stack of substacks, each a non-yellow head level followed by a run of
-- yellows.  A yellow top level belongs to the top run; a green one heads the
-- first substack, with 'tl' as its run.  Every field is strict.
--
-- Ys a b is a run of yellow levels from element type a down to b.  Every
-- level below the top holds Nodes, which the GADT constructors record.

data Ys a b where
  YN :: Ys a a
  YC :: {-# UNPACK #-} !(Lvl (Node a)) -> !(Ys (Node (Node a)) b) -> Ys (Node a) b

data Sub a b = Sub {-# UNPACK #-} !(Lvl a) !(Ys (Node a) b)

data Subs a where
  SN :: Subs a
  SC :: !(Sub (Node x) b) -> !(Subs b) -> Subs (Node x)

data Deque a where
  Nil :: Deque a
  -- total element count, prefix (count, elements), suffix (count, elements),
  -- yellow run below, substacks.  (The top digits are kept as plain fields so
  -- that the fast paths carry no leaf counts.)
  Deque :: {-# UNPACK #-} !Int -> {-# UNPACK #-} !Int -> !(SList a) -> {-# UNPACK #-} !Int -> !(SList a) -> !(Ys (Node a) b) -> !(Subs b) -> Deque a

isYN :: Ys a b -> Bool
isYN YN = True
isYN _  = False

isSN :: Subs a -> Bool
isSN SN = True
isSN _  = False

empty :: Deque a
empty = Nil

mkDeque :: Int -> Dig a -> Dig a -> Ys (Node a) b -> Subs b -> Deque a
mkDeque sz (Dig n _ l) (Dig m _ r) tl subs = Deque sz n l m r tl subs
{-# INLINE mkDeque #-}

lcolorD :: Bool -> Dig a -> Dig a -> Color
lcolorD bottom p s = lcolorN bottom (dcount p) (dcount s)
{-# INLINE lcolorD #-}

-- Put a modified top level back.  sz is the new total size, (np, ns) the old
-- top's digit sizes, (p', s') the new digits.
-- Only a red result, or a green head turning yellow, can expose a red first
-- non-yellow level, so only those cases look further down.
place :: Int -> Int -> Int -> Dig a -> Dig a -> Ys (Node a) b -> Subs b -> Deque a
place !sz !np !ns p' s' tl subs
  | bottom && dcount p' == 0 && dcount s' == 0 = Nil
  | otherwise = case lcolorD bottom p' s' of
      Green  -> mkDeque sz p' s' tl subs
      Yellow | lcolorN bottom np ns == Yellow -> mkDeque sz p' s' tl subs
             | otherwise                      -> mkDeque sz p' s' tl (regularizeSubs subs)
      Red    -> fixTopRed sz p' s' tl subs
  where bottom = isYN tl && isSN subs

-- One end of a repair: a digit above bGreen sheds a node downward, a digit
-- below 2 pulls one up, anything else is left alone.
actP, actS :: (Dig a -> (Dig a, Node a)) -> Dig a -> Dig (Node a) -> (Dig a -> Dig (Node a) -> r) -> r
actP shP p lp k
  | np > bGreen = case shP p of (p', nd) -> k p' (dpushS nodeSize nd lp)
  | np < 2      = case dpopS nodeSize lp of (nd, lp') -> k (pullP p nd) lp'
  | otherwise   = k p lp
  where np = dcount p
actS shS s ls k
  | ns > bGreen = case shS s of (s', nd) -> k s' (dpushS nodeSize nd ls)
  | ns < 2      = case dpopS nodeSize ls of (nd, ls') -> k (pullS s nd) ls'
  | otherwise   = k s ls
  where ns = dcount s
{-# INLINE actP #-}
{-# INLINE actS #-}

-- Repair a red level (p, s) given the level below it.  When that level is
-- not the bottom, both of its digits are non-empty and non-full, so the
-- moves are straight list operations with no intermediate allocation (the
-- same goes for a bottom level with enough in the digits that are needed);
-- everything else goes through the general makeGreen.  kJ gets the new
-- digits and the new level below; kN just the new digits when the level
-- below vanished.
repair :: (Dig a -> (Dig a, Node a)) -> (Dig a -> (Dig a, Node a)) -> (a -> Int)
       -> Dig a -> Dig a -> Maybe (Lvl (Node a)) -> Bool
       -> (Dig a -> Dig a -> Lvl (Node a) -> r) -> (Dig a -> Dig a -> r) -> r
repair shP shS sz p s ml0 nextLast kJ kN = case ml0 of
    Just (Lvl lp ls) | not nextLast || bottomSupplies lp ls ->
      actP shP p lp (\p1 lp1 -> actS shS s ls (\s1 ls1 -> kJ p1 s1 (Lvl lp1 ls1)))
    _ -> slow
  where
    -- a bottom level may have an empty digit, and must not be left empty
    bottomSupplies lp ls =
      let needP = if dcount p < 2 then 1 else 0 :: Int
          needS = if dcount s < 2 then 1 else 0
      in dcount lp >= needP && dcount ls >= needS && dcount lp + dcount ls > needP + needS
    slow = case makeGreen shP shS sz nextLast (Lvl p s) ml0 of
      (Lvl p' s', Nothing)  -> kN p' s'
      (Lvl p' s', Just l1') -> kJ p' s' l1'
{-# INLINE repair #-}

fixTopRed :: Int -> Dig a -> Dig a -> Ys (Node a) b -> Subs b -> Deque a
fixTopRed sz p s tl subs = case tl of
  YC l1 yt -> fixVia sz p s l1 yt subs
  YN -> case subs of
    SC (Sub l1 yt) st -> fixVia sz p s l1 yt st
    -- the only level, and what it holds fits in two green digits: rebalance
    SN | dcount p + dcount s <= 2 * bGreen ->
           case canonBottom (const 0) (Lvl p s) of Lvl p' s' -> mkDeque sz p' s' YN SN
    SN -> repair shedP shedS (const 0) p s Nothing True
            (\p' s' l1' -> case lcolor True l1' of
                 Yellow -> mkDeque sz p' s' (YC l1' YN) SN
                 _      -> mkDeque sz p' s' YN (SC (Sub l1' YN) SN))
            (\p' s' -> mkDeque sz p' s' YN SN)

fixVia :: Int -> Dig a -> Dig a -> Lvl (Node a) -> Ys (Node (Node a)) c -> Subs c -> Deque a
fixVia sz p s l1 yt st =
  let lst = isYN yt && isSN st
  in repair shedP shedS (const 0) p s (Just l1) lst
       (\p' s' l1' -> case lcolor lst l1' of
            Yellow -> mkDeque sz p' s' (YC l1' yt) st
            _      -> mkDeque sz p' s' YN (SC (Sub l1' yt) st))
       (\p' s' -> mkDeque sz p' s' YN SN)

-- Fix the red head of the first substack (r, rest); 'subs' follow it.
fixSub :: Lvl (Node x) -> Ys (Node (Node x)) b -> Subs b -> Subs (Node x)
fixSub (Lvl p s) rest subs = case rest of
  YC l1 yt -> fixSubVia p s l1 yt subs
  YN -> case subs of
    SC (Sub l1 yt) st -> fixSubVia p s l1 yt st
    SN -> repair shedPN shedSN nodeSize p s Nothing True
            (\p' s' l1' -> case lcolor True l1' of
                 Yellow -> SC (Sub (Lvl p' s') (YC l1' YN)) SN
                 _      -> SC (Sub (Lvl p' s') YN) (SC (Sub l1' YN) SN))
            (\p' s' -> SC (Sub (Lvl p' s') YN) SN)

fixSubVia :: Dig (Node x) -> Dig (Node x) -> Lvl (Node (Node x)) -> Ys (Node (Node (Node x))) c -> Subs c -> Subs (Node x)
fixSubVia p s l1 yt st =
  let lst = isYN yt && isSN st
  in repair shedPN shedSN nodeSize p s (Just l1) lst
       (\p' s' l1' -> case lcolor lst l1' of
            Yellow -> SC (Sub (Lvl p' s') (YC l1' yt)) st
            _      -> SC (Sub (Lvl p' s') YN) (SC (Sub l1' yt) st))
       (\p' s' -> SC (Sub (Lvl p' s') YN) SN)

regularizeSubs :: Subs a -> Subs a
regularizeSubs (SC (Sub r rest) subs)
  | lcolor (isYN rest && isSN subs) r == Red = fixSub r rest subs
regularizeSubs subs = subs

------------------------------------------------------------------------
-- The operations

-- Fast paths.  If the digit being changed keeps its color, the level's color
-- is unchanged, so nothing below can be affected and no repair is needed:
--   cons/snoc  onto a digit of size 1..bGreen-1   (yellow/green -> green/yellow-or-green)
--   uncons     from a digit of size 3..bGreen+1
-- A digit growing from bGreen to bGreen+1 turns green->yellow, which can only
-- matter if the level was green (it then stops heading a substack, and the
-- next head must be checked).  Everything else goes through 'place' in
-- NOINLINE slow-path functions that take the digits' fields unpacked, so no
-- Dig boxes are allocated on the fast path.  The wrappers are INLINE so that,
-- at a call site, the Maybe/tuple/Deque cells of a fast-path operation vanish.

cons :: a -> Deque a -> Deque a
cons x Nil = Deque 1 1 (SCons x SEmpty) 0 SEmpty YN SN
cons x (Deque sz n l m r tl subs)
  | n >= 1 && n < bGreen = Deque (sz + 1) (n + 1) (SCons x l) m r tl subs
  | n == bGreen          = Deque (sz + 1) (n + 1) (SCons x l) m r tl (greenToYellow n m tl subs)
  | otherwise            = consSlow x sz n l m r tl subs
{-# INLINE cons #-}

snoc :: Deque a -> a -> Deque a
snoc Nil x = Deque 1 0 SEmpty 1 (SCons x SEmpty) YN SN
snoc (Deque sz n l m r tl subs) x
  | m >= 1 && m < bGreen = Deque (sz + 1) n l (m + 1) (SCons x r) tl subs
  | m == bGreen          = Deque (sz + 1) n l (m + 1) (SCons x r) tl (greenToYellow m n tl subs)
  | otherwise            = snocSlow x sz n l m r tl subs
{-# INLINE snoc #-}

-- The top level (digit sizes d, e) goes from green to yellow because digit d
-- grew past bGreen: if it was green, the first substack head may now be exposed.
greenToYellow :: Int -> Int -> Ys (Node a) b -> Subs b -> Subs b
greenToYellow d e tl subs
  | lcolorN (isYN tl && isSN subs) d e == Green = regularizeSubs subs
  | otherwise                                   = subs
{-# INLINE greenToYellow #-}

consSlow :: a -> Int -> Int -> SList a -> Int -> SList a -> Ys (Node a) b -> Subs b -> Deque a
consSlow x !sz !n l !m r tl subs =
  place (sz + 1) n m (Dig (n + 1) 0 (SCons x l)) (Dig m 0 r) tl subs
{-# NOINLINE consSlow #-}

snocSlow :: a -> Int -> Int -> SList a -> Int -> SList a -> Ys (Node a) b -> Subs b -> Deque a
snocSlow x !sz !n l !m r tl subs =
  place (sz + 1) n m (Dig n 0 l) (Dig (m + 1) 0 (SCons x r)) tl subs
{-# NOINLINE snocSlow #-}

uncons :: Deque a -> Maybe (a, Deque a)
uncons Nil = Nothing
uncons (Deque sz n l m r tl subs) = case l of
  SCons x l' | n >= 3                           -- (a top digit has at most bGreen + 1)
             -> Just (x, Deque (sz - 1) (n - 1) l' m r tl subs)
             | YN <- tl, SN <- subs             -- the only level: no colors to keep
             -> if sz == 1 then Just (x, Nil) else Just (x, Deque (sz - 1) (n - 1) l' m r YN SN)
  _          -> unconsSlow sz n l m r tl subs
{-# INLINE uncons #-}

unconsSlow :: Int -> Int -> SList a -> Int -> SList a -> Ys (Node a) b -> Subs b -> Maybe (a, Deque a)
unconsSlow !sz !n l !m r tl subs
  | isYN tl, isSN subs = case l of              -- the only level: no colors to keep
      SCons x l'
        | sz == 1   -> Just (x, Nil)
        | otherwise -> Just (x, Deque (sz - 1) (n - 1) l' m r YN SN)
      -- everything is in the suffix: leave half of what remains there (all
      -- of it goes to the prefix if that is three elements or fewer)
      SEmpty -> let !rm = m - 1
                    !k  = if rm <= 3 then 0 else rm `div` 2
                in case revS (dropS k r) of
                     SCons x l' | rm == 0   -> Just (x, Nil)
                                | otherwise -> Just (x, Deque rm (rm - k) l' k (takeS k r) YN SN)
                     SEmpty -> Nothing
  | n > 0 = case dpop p of
      (x, p') -> let !d = place (sz - 1) n m p' (Dig m 0 r) tl subs in Just (x, d)
  | otherwise = case popF (const 0) (Lvl p s) of      -- bottom level with empty prefix
      Just (x, Lvl p' s') -> let !d = place (sz - 1) n m p' s' tl subs in Just (x, d)
      Nothing             -> Nothing
  where p = Dig n 0 l; s = Dig m 0 r
{-# NOINLINE unconsSlow #-}

unsnoc :: Deque a -> Maybe (Deque a, a)
unsnoc Nil = Nothing
unsnoc (Deque sz n l m r tl subs) = case r of
  SCons x r' | m >= 3
             -> Just (Deque (sz - 1) n l (m - 1) r' tl subs, x)
             | YN <- tl, SN <- subs
             -> if sz == 1 then Just (Nil, x) else Just (Deque (sz - 1) n l (m - 1) r' YN SN, x)
  _          -> unsnocSlow sz n l m r tl subs
{-# INLINE unsnoc #-}

unsnocSlow :: Int -> Int -> SList a -> Int -> SList a -> Ys (Node a) b -> Subs b -> Maybe (Deque a, a)
unsnocSlow !sz !n l !m r tl subs
  | isYN tl, isSN subs = case r of
      SCons x r'
        | sz == 1   -> Just (Nil, x)
        | otherwise -> Just (Deque (sz - 1) n l (m - 1) r' YN SN, x)
      SEmpty -> let !rm = n - 1
                    !k  = if rm <= 3 then 0 else rm `div` 2      -- these stay in the prefix
                in case revS (dropS k l) of
                     SCons x r' | rm == 0   -> Just (Nil, x)
                                | otherwise -> Just (Deque rm k (takeS k l) (rm - k) r' YN SN, x)
                     SEmpty -> Nothing
  | m > 0 = case dpop s of
      (x, s') -> let !d = place (sz - 1) n m (Dig n 0 l) s' tl subs in Just (d, x)
  | otherwise = case popB (const 0) (Lvl p s) of      -- bottom level with empty suffix
      Just (x, Lvl p' s') -> let !d = place (sz - 1) n m p' s' tl subs in Just (d, x)
      Nothing             -> Nothing
  where p = Dig n 0 l; s = Dig m 0 r
{-# NOINLINE unsnocSlow #-}

