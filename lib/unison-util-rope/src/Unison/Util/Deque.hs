pattern Empty :: Deque a
pattern Empty <- (null -> True) where
  Empty = Nil

pattern (:<|) :: a -> Deque a -> Deque a
pattern x :<| xs <- (uncons -> Just (x, xs)) where
  x :<| xs = cons x xs

pattern (:|>) :: Deque a -> a -> Deque a
pattern xs :|> x <- (unsnoc -> Just (xs, x)) where
  xs :|> x = snoc xs x

