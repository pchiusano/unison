-- | A stable sort.  O(n log n); goes through a list.
sort :: (Ord a) => Deque a -> Deque a
sort = sortBy compare

sortBy :: (a -> a -> Ordering) -> Deque a -> Deque a
sortBy cmp = fromList . L.sortBy cmp . toList

