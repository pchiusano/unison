-- take and drop.
--
-- Cutting at a position is the same descent as 'lookup'.  To remove the first
-- k leaves, find the level whose digit holds the cut.  The cut element, if
-- the cut falls inside it (a node), is split: its remaining children become
-- the new outer digit of the level above, and the child containing the cut
-- is split in turn one level up, so every level above the cut ends up with a
-- fresh outer digit of at most seven elements and an untouched inner digit.
-- If the cut lies in an inner digit, everything below that level is gone and
-- the level becomes the bottom.  Levels below the cut are shared with the
-- original.  On the way back up each level is put on top of the (regular)
-- levels below it with 'mkRest', which repairs it if its new digit came out
-- empty.  O(log n).  'take' is the mirror image (remove from the back), so
-- both share the code, parametrized by which digit is "near" the cut end.

-- (near digit, far digit)
nearFar :: Bool -> Lvl x -> (Dig x, Dig x)
nearFar True  (Lvl p s) = (p, s)
nearFar False (Lvl p s) = (s, p)
{-# INLINE nearFar #-}

fromNearFar :: Bool -> Dig x -> Dig x -> Lvl x
fromNearFar True  n f = Lvl n f
fromNearFar False n f = Lvl f n
{-# INLINE fromNearFar #-}

-- an element the cut falls inside, with the number of leaves to cut from its near end
data Part x = NoPart | Part !x !Int

-- Remove k leaves from the near end of a list (near end first) of n elements
-- and z leaves, k <= z.  Gives what remains (count, leaves, list); an element
-- the cut falls inside is removed too, and returned.
cutDig :: (x -> Int) -> Int -> Int -> Int -> SList x -> (# Int, Int, SList x, Part x #)
cutDig sz = go
  where
    go !k !n !z l
      | k == 0 = (# n, z, l, NoPart #)
      | otherwise = case l of
          SCons e r -> let !ze = sz e
                       in if k < ze then (# n - 1, z - ze, r, Part e k #)
                          else go (k - ze) (n - 1) (z - ze) r
          SEmpty -> error "cutDig: out of range"
{-# INLINE cutDig #-}

-- Remove k leaves (of tot) from the near end of these levels.  If the cut falls inside an element of the first level, that
-- element is removed and returned: its children beyond the cut belong to the
-- level above.
cutRest :: Bool -> Int -> Int -> Rest (Node a) -> (# Rest (Node a), Part (Node a) #)
cutRest fwd !k !tot rest
  | k == 0 = (# rest, NoPart #)
  | otherwise = case viewRest rest of
      Nothing -> error "cutRest: out of levels"
      Just (l, rest1) -> case nearFar fwd l of
        (Dig cn zn nl, f@(Dig cf zf fl))
          | k < zn -> case cutDig nodeSize k cn zn nl of
              (# c', z', l', part #) ->
                (# mkRest (fromNearFar fwd (Dig c' z' l') f) rest1, part #)
          | k < tot - zf -> case cutRest fwd (k - zn) (tot - zn - zf) rest1 of
              (# rest1', NoPart #) -> (# mkRest (fromNearFar fwd dnil f) rest1', NoPart #)
              (# rest1', Part e o #) ->
                case cutDig nodeSize o (nodeArity e) (nodeSize e) (if fwd then nodeToFwd e else nodeToBwd e) of
                  (# c', z', l', part #) -> (# mkRest (fromNearFar fwd (Dig c' z' l') f) rest1', part #)
          -- in the far digit: this level becomes the bottom
          | otherwise -> case cutDig nodeSize (k - (tot - zf)) cf zf (revS fl) of
              (# c', z', l', part #) -> (# mkRest (fromNearFar fwd (Dig c' z' l') dnil) noRest, part #)

drop :: Int -> Deque a -> Deque a
drop _ Nil = Nil
drop i d@(Deque sz np pl ns sl tl subs)
  | i <= 0      = d
  | i >= sz     = Nil
  | i < np      = mkTop (sz - i) (Dig (np - i) 0 (dropS i pl)) (Dig ns 0 sl) (Rest tl subs)
  | i < sz - ns = case cutRest True (i - np) (sz - np - ns) (Rest tl subs) of
      (# rest, NoPart #)   -> mkTop (sz - i) dnil (Dig ns 0 sl) rest
      (# rest, Part e o #) -> mkTop (sz - i) (Dig (nodeArity e - o) 0 (dropS o (nodeToFwd e))) (Dig ns 0 sl) rest
  | otherwise   = let c = sz - i                  -- what is left is the end of the suffix
                  in Deque c 0 SEmpty c (takeS c sl) YN SN

take :: Int -> Deque a -> Deque a
take _ Nil = Nil
take i d@(Deque sz np pl ns sl tl subs)
  | i <= 0      = Nil
  | i >= sz     = d
  | k < ns      = mkTop i (Dig np 0 pl) (Dig (ns - k) 0 (dropS k sl)) (Rest tl subs)
  | k < sz - np = case cutRest False (k - ns) (sz - np - ns) (Rest tl subs) of
      (# rest, NoPart #)   -> mkTop i (Dig np 0 pl) dnil rest
      (# rest, Part e o #) -> mkTop i (Dig np 0 pl) (Dig (nodeArity e - o) 0 (dropS o (nodeToBwd e))) rest
  | otherwise   = Deque i i (takeS i pl) 0 SEmpty YN SN      -- the start of the prefix
  where k = sz - i                                -- to remove from the back

