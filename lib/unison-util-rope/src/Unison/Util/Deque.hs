-- Checking (for tests)

-- | Check the invariants the operations rely on.  @Left@ describes the first
-- violation found.  O(n).
--
-- * the stored counts are right: the total, each digit's length and leaf
--   count, each node's size
-- * no digit has more than @bGreen + 2@ elements and the bottom level isn't empty
-- * the levels are regular: ignoring yellow levels, the first is green and no
--   two red ones are adjacent
-- * the levels are grouped by color: runs hold yellow levels only, and every
--   substack is headed by a level that isn't yellow
valid :: Deque a -> Either String ()
valid Nil = Right ()
valid d@(Deque sz _ _ _ _ tl subs) = do
  (total, colors) <- checkRaw True (const (Right 1)) (toRaw d)
  unless (total == sz) $ Left ("the size is " ++ show sz ++ " but there are " ++ show total ++ " elements")
  case filter (/= Yellow) colors of
    Red : _ -> Left ("the first level that isn't yellow is red: " ++ show colors)
    cs | or (zipWith (\a b -> a == Red && b == Red) cs (L.drop 1 cs)) ->
           Left ("two red levels with no green one between them: " ++ show colors)
    _ -> Right ()
  zipWithM_ grouped (L.drop 1 colors) (replicate (lenYs tl) False ++ subHeads subs)
  where
    grouped c isHead
      | isHead && c == Yellow     = Left "a substack is headed by a yellow level"
      | not isHead && c /= Yellow = Left ("a " ++ show c ++ " level in a run of yellow ones")
      | otherwise                 = Right ()

lenYs :: Ys a b -> Int
lenYs YN       = 0
lenYs (YC _ r) = 1 + lenYs r

-- one Bool per level below the top run: is it the head of a substack?
subHeads :: Subs a -> [Bool]
subHeads SN                     = []
subHeads (SC (Sub _ r) rest)    = True : (replicate (lenYs r) False ++ subHeads rest)

-- the number of leaves under these levels and the levels' colors, top first
checkRaw :: Bool -> (x -> Either String Int) -> Raw x -> Either String (Int, [Color])
checkRaw _ _ RNil = Right (0, [])
checkRaw top leaves (RCons (Lvl p s) rest) = do
  zp <- checkDig top leaves p
  zs <- checkDig top leaves s
  (zr, cs) <- checkRaw False (checkNode leaves) rest
  let bottom = isRNil rest
  when (bottom && dcount p + dcount s == 0) $ Left "the bottom level is empty"
  pure (zp + zs + zr, lcolorN bottom (dcount p) (dcount s) : cs)

checkDig :: Bool -> (x -> Either String Int) -> Dig x -> Either String Int
checkDig top leaves (Dig n z l) = do
  zs <- traverse leaves (listS l)
  unless (n == L.length zs) $ Left ("a digit of " ++ show (L.length zs) ++ " elements has count " ++ show n)
  when (n > bGreen + 2) $ Left ("a digit has " ++ show n ++ " elements")
  unless (top || z == sum zs) $ Left ("a digit with " ++ show (sum zs) ++ " leaves has leaf count " ++ show z)
  pure (sum zs)

checkNode :: (x -> Either String Int) -> Node x -> Either String Int
checkNode leaves nd = do
  zs <- traverse leaves (listS (nodeToFwd nd))
  unless (sum zs == nodeSize nd) $ Left ("a node with " ++ show (sum zs) ++ " leaves has size " ++ show (nodeSize nd))
  pure (nodeSize nd)

