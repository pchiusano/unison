-- Folds.  These walk the structure directly: prefix, the levels below, then
-- the suffix (whose list runs back to front).  Below the top level an element
-- is a node, so the function handed down folds over a node's children.

-- | Right fold, lazy in the accumulator.
foldrD :: (a -> r -> r) -> r -> Deque a -> r
foldrD _ z Nil = z
foldrD f z (Deque _ _ l _ r tl subs) =
  foldrFwd f (foldrYs (foldrNode f) tl subs (foldrBwd f z r)) l

-- The same, inlined where it is used, so that a known function is applied
-- directly to the children of the leaf nodes, where nearly all the elements
-- are.  With (:) that builds a leaf's eight cells with no calls in between.
foldrI :: (a -> r -> r) -> r -> Deque a -> r
foldrI _ z Nil = z
foldrI f z (Deque _ _ l _ r tl subs) =
  foldrFwd f (foldrYs (\nd acc -> foldrNodeI f nd acc) tl subs (foldrBwd f z r)) l
{-# INLINE foldrI #-}

foldrNodeI :: (x -> r -> r) -> Node x -> r -> r
foldrNodeI f (N8 _ a b c d e g h i) z = f a (f b (f c (f d (f e (f g (f h (f i z)))))))
foldrNodeI f (N3 _ a b c) z           = f a (f b (f c z))
foldrNodeI f (N2 _ a b) z             = f a (f b z)
{-# INLINE foldrNodeI #-}

-- a list in sequence order / a list that runs back to front (a short one)
foldrFwd, foldrBwd :: (x -> r -> r) -> r -> SList x -> r
foldrFwd f z = go where go SEmpty = z
                        go (SCons x r) = f x (go r)
foldrBwd f = go where go acc SEmpty = acc
                      go acc (SCons x r) = go (f x acc) r

foldrNode :: (x -> r -> r) -> Node x -> r -> r
foldrNode f (N8 _ a b c d e g h i) z = f a (f b (f c (f d (f e (f g (f h (f i z)))))))
foldrNode f (N3 _ a b c) z           = f a (f b (f c z))
foldrNode f (N2 _ a b) z             = f a (f b z)

foldrYs :: (x -> r -> r) -> Ys x b -> Subs b -> r -> r
foldrYs f YN subs z = foldrSubs f subs z
foldrYs f (YC (Lvl (Dig _ _ p) (Dig _ _ s)) rest) subs z =
  foldrFwd f (foldrYs (foldrNode f) rest subs (foldrBwd f z s)) p

foldrSubs :: (x -> r -> r) -> Subs x -> r -> r
foldrSubs _ SN z = z
foldrSubs f (SC (Sub (Lvl (Dig _ _ p) (Dig _ _ s)) rest) more) z =
  foldrFwd f (foldrYs (foldrNode f) rest more (foldrBwd f z s)) p

-- | Strict left fold.
foldlD' :: (r -> a -> r) -> r -> Deque a -> r
foldlD' _ !z Nil = z
foldlD' f !z (Deque _ _ l _ r tl subs) =
  foldlBwd f (foldlYs (foldlNode f) (foldlFwd f z l) tl subs) r

foldlFwd, foldlBwd :: (r -> x -> r) -> r -> SList x -> r
foldlFwd f = go where go !acc SEmpty = acc
                      go !acc (SCons x r) = go (f acc x) r
foldlBwd f !z = go where go SEmpty = z                      -- at most a digit deep
                         go (SCons x r) = let !acc = go r in f acc x

foldlNode :: (r -> x -> r) -> r -> Node x -> r
foldlNode f !z (N8 _ a b c d e g h i) =
  let !z1 = f z a; !z2 = f z1 b; !z3 = f z2 c; !z4 = f z3 d
      !z5 = f z4 e; !z6 = f z5 g; !z7 = f z6 h
  in f z7 i
foldlNode f !z (N3 _ a b c) = let !z1 = f z a; !z2 = f z1 b in f z2 c
foldlNode f !z (N2 _ a b)   = let !z1 = f z a in f z1 b

foldlYs :: (r -> x -> r) -> r -> Ys x b -> Subs b -> r
foldlYs f !z YN subs = foldlSubs f z subs
foldlYs f !z (YC (Lvl (Dig _ _ p) (Dig _ _ s)) rest) subs =
  foldlBwd f (foldlYs (foldlNode f) (foldlFwd f z p) rest subs) s

foldlSubs :: (r -> x -> r) -> r -> Subs x -> r
foldlSubs _ !z SN = z
foldlSubs f !z (SC (Sub (Lvl (Dig _ _ p) (Dig _ _ s)) rest) more) =
  foldlBwd f (foldlYs (foldlNode f) (foldlFwd f z p) rest more) s

