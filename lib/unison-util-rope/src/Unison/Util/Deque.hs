-- The levels from some depth down, as a value: a run of yellow levels, then
-- substacks.  This is what a Deque holds below its top level, and what any
-- level has below it.  We call it regular if its first level that isn't
-- yellow is green (or there is none): then it can sit under any level, a red
-- one included.

data Rest x where
  Rest :: !(Ys x b) -> !(Subs b) -> Rest x

noRest :: Rest (Node x)
noRest = Rest YN SN

-- the first level and what is below it
viewRest :: Rest (Node a) -> Maybe (Lvl (Node a), Rest (Node (Node a)))
viewRest (Rest (YC l r) subs)            = Just (l, Rest r subs)
viewRest (Rest YN (SC (Sub l r) st))     = Just (l, Rest r st)
viewRest (Rest YN SN)                    = Nothing
{-# INLINE viewRest #-}

isNoRest :: Rest x -> Bool
isNoRest (Rest ys subs) = isYN ys && isSN subs

-- Put a level with any digits (0 to bGreen + 2 elements each) on top of
-- levels that were regular under whatever they came from; the result is
-- regular.  Under a green level anything goes; otherwise the levels below
-- are made regular first, and a red level is then repaired, which moves at
-- most one node per end between it and the level below.
mkRest :: Lvl (Node a) -> Rest (Node (Node a)) -> Rest (Node a)
mkRest l (Rest ys subs)
  | bottom && isEmptyLvl l = noRest
  | otherwise = case lcolor bottom l of
      Green  -> Rest YN (SC (Sub l ys) subs)
      Yellow -> Rest (YC l ys) (regularizeSubs subs)
      Red    -> Rest YN (fixSub l ys (regularizeSubs subs))
  where bottom = isYN ys && isSN subs

-- The same for the top level.
mkTop :: Int -> Dig a -> Dig a -> Rest (Node a) -> Deque a
mkTop sz p s (Rest tl subs)
  | bottom && dcount p == 0 && dcount s == 0 = Nil
  | otherwise = case lcolorD bottom p s of
      Green  -> mkDeque sz p s tl subs
      Yellow -> mkDeque sz p s tl (regularizeSubs subs)
      Red    -> fixTopRed sz p s tl (regularizeSubs subs)
  where bottom = isYN tl && isSN subs

