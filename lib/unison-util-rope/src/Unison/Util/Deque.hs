-- Inspection

-- | The elements in order.  Lazy: the list is produced as it is consumed.
toList :: Deque a -> [a]
toList = foldrI (:) []

fromList :: [a] -> Deque a
fromList = L.foldl' snoc empty

-- | @fromFunction n f@ is @f 0, f 1, ..., f (n - 1)@.
fromFunction :: Int -> (Int -> a) -> Deque a
fromFunction n f
  | n < 0     = error "Deque.fromFunction called with negative len"
  | otherwise = go 0 empty
  where go !i !acc | i == n    = acc
                   | otherwise = go (i + 1) (snoc acc (f i))

singleton :: a -> Deque a
singleton x = Deque 1 1 (SCons x SEmpty) 0 SEmpty YN SN

-- O(1): the total is stored in the Deque.
size :: Deque a -> Int
size Nil            = 0
size (Deque sz _ _ _ _ _ _) = sz

-- Direct lookup by position.  Walk the levels top to bottom with polymorphic recursion.
-- At each level we look for the leaf with i leaves before it and j after it
-- (within the sequence of this level and everything below).  A hit in a digit
-- is a scan over the digit's elements, adding up their sizes; otherwise the
-- leaf lies in the part below, which hands back the element of the level
-- below containing it, and we pick the right child.  Results flow upward in
-- unboxed tuples, so no closures or intermediate lists are built: the only
-- allocation is the final Just.
lookup :: Int -> Deque a -> Maybe a
lookup !_ Nil = Nothing
lookup !i (Deque n np pl ns sl tl subs)
  | i < 0 || i >= n = Nothing
  | i < np          = let !r = nthS i pl in Just r
  | j < ns          = let !r = nthS j sl in Just r
  | otherwise       = case findYs 3 (i - np) (j - ns) tl subs of
                        (# nd, off# #) -> let !r = nodeAt (I# off#) nd in Just r
  where !j = n - 1 - i

nthS :: Int -> SList a -> a
nthS k (SCons x r) | k == 0    = x
                   | otherwise = nthS (k - 1) r
nthS _ SEmpty = error "nthS: out of range"

-- sh: log2 of the number of leaves under a full element of this level
findYs :: Int -> Int -> Int -> Ys x b -> Subs b -> (# x, Int# #)
findYs !sh !i !j YN subs          = findSubs sh i j subs
findYs !sh !i !j (YC l r) subs    = findLvl sh i j l r subs

findSubs :: Int -> Int -> Int -> Subs x -> (# x, Int# #)
findSubs _ _ _ SN = error "index: ran out of levels"
findSubs !sh !i !j (SC (Sub l r) rest) = findLvl sh i j l r rest

findLvl :: Int -> Int -> Int -> Lvl (Node a) -> Ys (Node (Node a)) b -> Subs b -> (# Node a, Int# #)
findLvl !sh !i !j (Lvl (Dig _ zp pl) (Dig _ zs sl)) r rest
  | i < zp    = scanFront i pl
  | j < zs    = scanBack j sl
  | otherwise = case findYs (sh + 3) (i - zp) (j - zs) r rest of
                  (# nd, o# #) -> childAt sh (I# o#) nd

-- the node holding the leaf with k leaves before it in a digit that has it
scanFront :: Int -> SList (Node a) -> (# Node a, Int# #)
scanFront !k (SCons e r) = let !z = nodeSize e
                           in if k < z then (case k of I# k# -> (# e, k# #)) else scanFront (k - z) r
scanFront _ SEmpty = error "scanFront"

-- ... or with k leaves after it, in a suffix digit (its list runs from the back)
scanBack :: Int -> SList (Node a) -> (# Node a, Int# #)
scanBack !k (SCons e r) = let !z = nodeSize e
                          in if k < z then (case z - 1 - k of I# o# -> (# e, o# #)) else scanBack (k - z) r
scanBack _ SEmpty = error "scanBack"

-- the child of a node (of nodes) containing leaf offset k, and the offset in it
childAt :: Int -> Int -> Node (Node y) -> (# Node y, Int# #)
childAt !sh !k0 nd = case nd of
  N8 sz a b c d e f g h
    | sz == 8 `unsafeShiftL` sh -> case nodeAt (k0 `unsafeShiftR` sh) nd of     -- all children full
        c' -> fin c' (k0 .&. ((1 `unsafeShiftL` sh) - 1))
    | otherwise ->
    let !za = nodeSize a in if k0 < za then fin a k0 else
    let !k1 = k0 - za; !zb = nodeSize b in if k1 < zb then fin b k1 else
    let !k2 = k1 - zb; !zc = nodeSize c in if k2 < zc then fin c k2 else
    let !k3 = k2 - zc; !zd = nodeSize d in if k3 < zd then fin d k3 else
    let !k4 = k3 - zd; !ze = nodeSize e in if k4 < ze then fin e k4 else
    let !k5 = k4 - ze; !zf = nodeSize f in if k5 < zf then fin f k5 else
    let !k6 = k5 - zf; !zg = nodeSize g in if k6 < zg then fin g k6 else
    fin h (k6 - zg)
  N3 _ a b c ->
    let !za = nodeSize a in if k0 < za then fin a k0 else
    let !k1 = k0 - za; !zb = nodeSize b in if k1 < zb then fin b k1 else
    fin c (k1 - zb)
  N2 _ a b ->
    let !za = nodeSize a in if k0 < za then fin a k0 else fin b (k0 - za)
  where
    fin c k = case k of I# k# -> (# c, k# #)
    {-# INLINE fin #-}

