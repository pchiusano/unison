-- Raw view: a deque as a plain list of levels, top first (no color grouping).
-- Only the checker uses it.

data Raw a where
  RNil  :: Raw a
  RCons :: !(Lvl a) -> !(Raw (Node a)) -> Raw a

isRNil :: Raw a -> Bool
isRNil RNil = True
isRNil _    = False

ysRaw :: Ys x b -> Raw b -> Raw x
ysRaw YN rest        = rest
ysRaw (YC l r) rest  = RCons l (ysRaw r rest)

subsRaw :: Subs x -> Raw x
subsRaw SN = RNil
subsRaw (SC (Sub h r) rest) = RCons h (ysRaw r (subsRaw rest))

toRaw :: Deque a -> Raw a
toRaw Nil = RNil
toRaw (Deque _ n l m r tl subs) = RCons (Lvl (Dig n 0 l) (Dig m 0 r)) (ysRaw tl (subsRaw subs))

