-- More list helpers

lenS :: SList a -> Int
lenS = go 0 where go !acc SEmpty = acc
                  go !acc (SCons _ r) = go (acc + 1) r

revS :: SList a -> SList a
revS = go SEmpty where go acc SEmpty = acc
                       go acc (SCons x r) = go (SCons x acc) r

-- reverse xs onto acc
revApp :: SList a -> SList a -> SList a
revApp SEmpty acc       = acc
revApp (SCons x r) acc  = revApp r (SCons x acc)

listS :: SList a -> [a]
listS SEmpty      = []
listS (SCons x r) = x : listS r

-- the digit's elements as stored: in sequence order (prefix) / last-first (suffix)
dFwd, dBwd :: Dig a -> SList a
dFwd (Dig _ _ l) = l
dBwd (Dig _ _ l) = l

-- a digit from its count and elements
mkDig :: (x -> Int) -> Int -> SList x -> Dig x
mkDig sz n l = Dig n (sumSz sz l) l

sumSz :: (x -> Int) -> SList x -> Int
sumSz sz = go 0 where go !acc SEmpty = acc
                      go !acc (SCons x r) = go (acc + sz x) r

-- A digit without its innermost element, and that element.
dInit :: (x -> Int) -> Dig x -> (# Dig x, x #)
dInit sz (Dig n z l) = let !x = nthS (n - 1) l in (# Dig (n - 1) (z - sz x) (takeS (n - 1) l), x #)

-- Cut a forward list of m (0 or >= 2) elements into nodes in one pass: nodes
-- of eight while more than nine elements remain, then threes and twos.
packF :: (x -> Int) -> Int -> SList x -> SList (Node x)
packF sz = go
  where
    go !m l
      | m == 0 = SEmpty
      | m >= 10 || m == 8 = case l of
          SCons a (SCons b (SCons c (SCons d (SCons e (SCons f (SCons g (SCons h r))))))) ->
            SCons (N8 (sz a + sz b + sz c + sz d + sz e + sz f + sz g + sz h) a b c d e f g h) (go (m - 8) r)
          _ -> error "packF"
      | m == 3 || m == 5 || m == 6 || m == 7 || m == 9 = case l of
          SCons a (SCons b (SCons c r)) -> SCons (N3 (sz a + sz b + sz c) a b c) (go (m - 3) r)
          _ -> error "packF"
      | otherwise = case l of
          SCons a (SCons b r) -> SCons (N2 (sz a + sz b) a b) (go (m - 2) r)
          _ -> error "packF"
{-# INLINE packF #-}

